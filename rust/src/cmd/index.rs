//! `openclew index [docDir]` — regenerate doc/_INDEX.md (mirrors lib/index-gen.js).

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use crate::parse::collect::{collect_docs, Doc, DocKind};

const OPEN_STATUSES: &[&str] = &["open", "in progress", "in-progress", "wip", "blocked"];

pub struct IndexCounts {
    pub refs: usize,
    pub logs: usize,
    pub todos: usize,
}

fn or_dash(value: &str) -> &str {
    if value.is_empty() { "—" } else { value }
}

/// Project-relative link, always `/`-separated
fn rel_link(doc: &Doc, doc_dir: &Path) -> String {
    let parent = doc_dir.parent().unwrap_or(doc_dir);
    let rel = doc.filepath.strip_prefix(parent).unwrap_or(&doc.filepath);
    rel.to_string_lossy().replace('\\', "/")
}

/// First 10 chars of the filename (date prefix) as fallback date
fn filename_date(doc: &Doc) -> String {
    doc.filename.chars().take(10).collect()
}

fn is_open(doc: &Doc) -> bool {
    let status = doc.meta.status();
    status.is_empty() || OPEN_STATUSES.contains(&status.to_lowercase().as_str())
}

/// Generate _INDEX.md content. `timestamp` is injected so tests are deterministic.
pub fn generate_index(doc_dir: &Path, timestamp: &str) -> String {
    let docs = collect_docs(doc_dir);
    let refs: Vec<&Doc> = docs.iter().filter(|d| d.kind == DocKind::Ref).collect();
    let logs: Vec<&Doc> = docs.iter().filter(|d| d.kind == DocKind::Log).collect();
    let mut todos: Vec<&Doc> = docs.iter().filter(|d| d.kind == DocKind::Todo).collect();
    // Open first, then Done; newest first within each group
    todos.sort_by(|a, b| is_open(b).cmp(&is_open(a)).then_with(|| b.filename.cmp(&a.filename)));

    let mut lines: Vec<String> = vec![
        "# Project Knowledge Index".into(),
        String::new(),
        format!("> Auto-generated by [openclew](https://github.com/openclew/openclew) on {timestamp}."),
        "> Do not edit manually — rebuilt from L1 metadata on every commit.".into(),
        String::new(),
    ];

    lines.push("## Refs".into());
    lines.push(String::new());
    if refs.is_empty() {
        lines.push("_No refs yet. Create one with `npx openclew add ref \"Title\"`._".into());
    } else {
        lines.push("| Document | Subject | Status | Category |".into());
        lines.push("|----------|---------|--------|----------|".into());
        for d in &refs {
            lines.push(format!(
                "| [{}]({}) | {} | {} | {} |",
                d.filename,
                rel_link(d, doc_dir),
                or_dash(d.meta.subject()),
                or_dash(d.meta.status()),
                or_dash(d.meta.category())
            ));
        }
    }
    lines.push(String::new());

    lines.push("## TODOs".into());
    lines.push(String::new());
    if todos.is_empty() {
        lines.push("_No TODOs yet. Create one with `/oc-todo \"Title\"`._".into());
    } else {
        lines.push("| Created | Subject | Status | Priority |".into());
        lines.push("|---------|---------|--------|----------|".into());
        for d in &todos {
            let created = match d.meta.get("created").unwrap_or("") {
                "" => filename_date(d),
                c => c.to_string(),
            };
            lines.push(format!(
                "| {created} | [{}]({}) | {} | {} |",
                or_dash(d.meta.subject()),
                rel_link(d, doc_dir),
                or_dash(d.meta.status()),
                or_dash(d.meta.get("priority").unwrap_or(""))
            ));
        }
    }
    lines.push(String::new());

    lines.push("## Recent logs".into());
    lines.push(String::new());
    if logs.is_empty() {
        lines.push("_No logs yet. Create one with `npx openclew add log \"Title\"`._".into());
    } else {
        lines.push("| Date | Subject | Status | Category |".into());
        lines.push("|------|---------|--------|----------|".into());
        for d in logs.iter().take(20) {
            let date = match d.meta.get("date").unwrap_or("") {
                "" => filename_date(d),
                c => c.to_string(),
            };
            lines.push(format!(
                "| {date} | [{}]({}) | {} | {} |",
                or_dash(d.meta.subject()),
                rel_link(d, doc_dir),
                or_dash(d.meta.status()),
                or_dash(d.meta.category())
            ));
        }
        if logs.len() > 20 {
            lines.push(String::new());
            lines.push(format!("_{} older logs not shown._", logs.len() - 20));
        }
    }
    lines.push(String::new());

    lines.push("---".into());
    lines.push(format!("**{}** refs, **{}** todos, **{}** logs.", refs.len(), todos.len(), logs.len()));
    lines.push(String::new());

    lines.join("\n")
}

/// Write _INDEX.md to disk, return doc counts
pub fn write_index(doc_dir: &Path) -> std::io::Result<IndexCounts> {
    let timestamp = chrono::Local::now().format("%Y-%m-%d %H:%M").to_string();
    fs::write(doc_dir.join("_INDEX.md"), generate_index(doc_dir, &timestamp))?;
    let docs = collect_docs(doc_dir);
    let count = |k: DocKind| docs.iter().filter(|d| d.kind == k).count();
    Ok(IndexCounts { refs: count(DocKind::Ref), logs: count(DocKind::Log), todos: count(DocKind::Todo) })
}

pub fn run(doc_dir_arg: Option<String>) -> Result<(), String> {
    let doc_dir = match doc_dir_arg {
        Some(p) => PathBuf::from(p),
        None => env::current_dir().map_err(|e| format!("Cannot get cwd: {e}"))?.join("doc"),
    };
    if !doc_dir.exists() {
        return Err("No doc/ directory found. Run 'openclew init' first.".to_string());
    }
    let c = write_index(&doc_dir).map_err(|e| format!("Cannot write _INDEX.md: {e}"))?;
    println!("Generated doc/_INDEX.md ({} refs, {} todos, {} logs)", c.refs, c.todos, c.logs);
    Ok(())
}
